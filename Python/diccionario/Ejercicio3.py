# Diccionarios de ejemplo
diccionario1 = {'a': 1, 'b': 2}
diccionario2 = {'c': 3, 'd': 4}
diccionario3 = {'e': 5, 'f': 6}

# Concatenamos los diccionarios usando el operador **
diccionario_concatenado = {**diccionario1, **diccionario2, **diccionario3}

print("Diccionario concatenado:", diccionario_concatenado)
